"""Aggregate all runs into result tables and the pre-registered statistical tests.

Writes results/summary.json and results/tables.md
"""
import json
import sys
from pathlib import Path

import numpy as np
from scipy import stats as st

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import stats as S  # noqa: E402
from configs import BASELINE_POOL, CONFIGS, PROPOSED  # noqa: E402

IMAGE = ["clean", "lowlight", "uneven", "hand_occ", "body_occ", "background", "blur", "distance", "viewpoint",
         "combined"]
FEATURE = ["missing_rgb", "missing_pose", "missing_hand", "fast", "slow"]
PROTOCOLS = ["loso", "cross_domain", "random", "unseen_sentence"]
OUT = ROOT / "results"


def fmt(m, s=None, d=1):
    if m is None or (isinstance(m, float) and np.isnan(m)):
        return "–"
    return f"{m:.{d}f}" + (f" ± {s:.{d}f}" if s is not None and not np.isnan(s) else "")


def seed_summary(runs, cond="clean"):
    """Pooled-over-splits corpus metrics per seed -> mean, sd, 95% CI."""
    seeds = S.seeds_available(runs)
    if not seeds:
        return None
    out = {}
    for key, num, den in [("wer", "err", "n"), ("cer", "cerr", "cn")]:
        vals = []
        for s in seeds:
            e = n = 0
            for sp in runs.values():
                if cond not in sp[s]["conds"]:
                    return None
                for it in sp[s]["conds"][cond]["items"]:
                    e += it[num]; n += it[den]
            vals.append(100 * e / n)
        out[key] = dict(mean=float(np.mean(vals)), sd=float(np.std(vals, ddof=1)) if len(vals) > 1 else float("nan"),
                        median=float(np.median(vals)), ci=S.ci_mean(vals), per_seed=vals)
    # exact-match sentence accuracy and gloss P/R/F1
    acc, f1, pr, rc = [], [], [], []
    for s in seeds:
        items = [it for sp in runs.values() for it in sp[s]["conds"][cond]["items"]]
        tp = sum(i["tp"] for i in items); nh = sum(i["nh"] for i in items); n = sum(i["n"] for i in items)
        p, r = tp / max(nh, 1), tp / max(n, 1)
        acc.append(100 * np.mean([i["exact"] for i in items])); pr.append(100 * p); rc.append(100 * r)
        f1.append(100 * 2 * p * r / max(p + r, 1e-9))
    for k, v in [("sent_acc", acc), ("precision", pr), ("recall", rc), ("f1", f1)]:
        out[k] = dict(mean=float(np.mean(v)), sd=float(np.std(v, ddof=1)) if len(v) > 1 else float("nan"))
    out["n_seeds"] = len(seeds)
    out["val_wer"] = float(np.mean([sp[s]["val_wer"] for sp in runs.values() for s in seeds]))
    out["train_time_s"] = float(np.mean([sp[s]["train_time"] for sp in runs.values() for s in seeds]))
    out["params"] = next(iter(next(iter(runs.values())).values()))["params"]
    return out


def main():
    eff = json.loads((OUT / "efficiency.json").read_text()) if (OUT / "efficiency.json").exists() else {}
    runs = {c: {p: S.load(c, p) for p in PROTOCOLS} for c in CONFIGS}
    summary = {"per_config": {}, "tests": {}}
    for c in CONFIGS:
        summary["per_config"][c] = {}
        for p in PROTOCOLS:
            if not runs[c][p]:
                continue
            summary["per_config"][c][p] = {cond: seed_summary(runs[c][p], cond) for cond in IMAGE + FEATURE}
            summary["per_config"][c][p] = {k: v for k, v in summary["per_config"][c][p].items() if v}

    def get(c, p="loso", cond="clean", key="wer"):
        try:
            return summary["per_config"][c][p][cond][key]
        except KeyError:
            return None

    # ---------------- strong baseline: lowest mean validation WER on LOSO (no test data used)
    pool = [c for c in BASELINE_POOL if get(c, key="wer")]
    vals = {c: summary["per_config"][c]["loso"]["clean"]["val_wer"] for c in pool}
    baseline = min(vals, key=vals.get) if vals else None
    summary["baseline_selection"] = dict(pool_val_wer=vals, selected=baseline)

    lines = ["# Results tables (auto-generated by scripts/analyze.py)\n"]
    # trivial reference: the single gloss string that minimises training WER, output for every test item
    from data import make_splits, seq_sentence
    from glosses import load_gloss_table
    from metrics import corpus, per_item
    table = load_gloss_table()
    # sequence ids recovered from the saved runs (LOSO tests every sequence exactly once)
    ids = sorted({i for c in CONFIGS for sp in runs[c]["loso"].values() for r in sp.values() for i in r["test_ids"]})
    splits = make_splits(ids)
    cands = {tuple(v) for v in table.values()} | {("YOU",), ("I",), ("I", "YOU"), ("WHAT", "YOU"), ()}
    summary["constant_baseline"] = {}
    for proto in PROTOCOLS:
        items = []
        for sp in splits[proto]:
            tr = [table[seq_sentence(i)] for i in sp["train"]]
            best = min(cands, key=lambda c: sum(per_item(r, list(c))["err"] for r in tr[::3]))
            items += [per_item(table[seq_sentence(i)], list(best)) for i in sp["test"]]
        summary["constant_baseline"][proto] = dict(output=" ".join(best), **corpus(items))
    if baseline and runs[PROPOSED]["loso"]:
        # ---------------- primary comparison
        prim = S.compare(runs[PROPOSED]["loso"], runs[baseline]["loso"], "clean")
        summary["tests"]["primary"] = dict(proposed=PROPOSED, baseline=baseline, **prim)

        # ---------------- family R: robustness (LOSO test signers), two comparisons per condition
        famR = []
        for other in [baseline, "G_concat"]:
            for cond in IMAGE[1:] + FEATURE:
                try:
                    r = S.compare(runs[PROPOSED]["loso"], runs[other]["loso"], cond, iters=5000)
                    famR.append(dict(vs=other, **r))
                except Exception:  # noqa: BLE001  condition not evaluated yet
                    pass
        if famR:
            padj, rej = S.holm([r["perm_p"] for r in famR])
            for r, pa, rj in zip(famR, padj, rej):
                r["p_holm"], r["reject"] = pa, rj
        summary["tests"]["family_R"] = famR

        # ---------------- family G: generalisation protocols
        famG = []
        for other in [baseline, "G_concat"]:
            for p in ["cross_domain", "random", "unseen_sentence"]:
                if runs[PROPOSED][p] and runs[other][p]:
                    famG.append(dict(vs=other, protocol=p, **S.compare(runs[PROPOSED][p], runs[other][p], "clean", iters=5000)))
        if famG:
            padj, rej = S.holm([r["perm_p"] for r in famG])
            for r, pa, rj in zip(famG, padj, rej):
                r["p_holm"], r["reject"] = pa, rj
        summary["tests"]["family_G"] = famG

    # ---------------- family A: ablation, Friedman over (fold, seed) blocks + Holm post-hoc
    abl = [c for c in ["A_rgb", "B_pose", "C_hand", "D_rgb_pose_concat", "E_rgb_hand_concat", "F_pose_hand_concat",
                       "G_concat", "H_fixed_weight", "I_seq_attention", "J_gate", "K_rel_gate", "L_trel_gate"]
           if runs[c]["loso"]]
    if len(abl) >= 3:
        blocks, M = S.run_level_matrix(abl, "loso")
        if len(blocks) >= 5:
            fr = st.friedmanchisquare(*M.T)
            ranks = np.mean([st.rankdata(r) for r in M], 0)
            post = []
            for j, c in enumerate(abl):
                if c == PROPOSED:
                    continue
                d = M[:, abl.index(PROPOSED)] - M[:, j]
                p = st.wilcoxon(M[:, abl.index(PROPOSED)], M[:, j]).pvalue if np.any(d != 0) else 1.0
                post.append(dict(config=c, mean_diff=float(d.mean()), p=float(p)))
            padj, rej = S.holm([x["p"] for x in post])
            for x, pa, rj in zip(post, padj, rej):
                x["p_holm"], x["reject"] = pa, rj
            summary["tests"]["family_A"] = dict(configs=abl, n_blocks=len(blocks), friedman_chi2=float(fr.statistic),
                                                friedman_p=float(fr.pvalue), mean_ranks=dict(zip(abl, ranks.tolist())),
                                                posthoc_vs_proposed=post)

    # ================= markdown tables
    lines.append("## Main results — LOSO signer-independent, clean test (mean ± SD over seeds; lower WER is better)\n")
    lines.append("| Config | Modalities | Fusion | WER ↓ | 95% CI | CER ↓ | Sent. acc ↑ | Gloss F1 ↑ | Val WER | Params | ms/seq | seeds |")
    lines.append("|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for c, cfg in CONFIGS.items():
        s = summary["per_config"].get(c, {}).get("loso", {}).get("clean")
        if not s:
            continue
        e = eff.get("models", {}).get(c, {})
        lines.append(f"| {c} | {'+'.join(cfg['mods'])} | {cfg['fusion'] if len(cfg['mods']) > 1 else '–'} | "
                     f"{fmt(s['wer']['mean'], s['wer']['sd'])} | [{s['wer']['ci'][0]:.1f}, {s['wer']['ci'][1]:.1f}] | "
                     f"{fmt(s['cer']['mean'], s['cer']['sd'])} | {fmt(s['sent_acc']['mean'])} | {fmt(s['f1']['mean'])} | "
                     f"{s['val_wer']:.1f} | {s['params'] / 1e6:.2f}M | {fmt(e.get('latency_ms'), d=2)} | {s['n_seeds']} |")

    cb = summary["constant_baseline"]["loso"]
    lines.append(f"| *constant output '{cb['output']}' (no learning)* | – | – | {cb['wer']:.1f} | – | {cb['cer']:.1f} | "
                 f"{cb['sent_acc']:.1f} | {cb['f1']:.1f} | – | 0 | – | – |")
    lines.append("\n## All protocols — clean test WER (mean ± SD over seeds)\n")
    lines.append("| Config | Random (signer-dep.) | LOSO (signer-indep.) | DSLR→phone (cross-domain) | Unseen sentences |")
    lines.append("|---|---:|---:|---:|---:|")
    for c in CONFIGS:
        row = [fmt(get(c, p, "clean", "wer")["mean"], get(c, p, "clean", "wer")["sd"]) if get(c, p, "clean", "wer") else "–"
               for p in ["random", "loso", "cross_domain", "unseen_sentence"]]
        if any(r != "–" for r in row):
            lines.append(f"| {c} | " + " | ".join(row) + " |")
    lines.append("| *constant output (no learning)* | " + " | ".join(f"{summary['constant_baseline'][p]['wer']:.1f}"
                 for p in ["random", "loso", "cross_domain", "unseen_sentence"]) + " |")

    lines.append("\n## Robustness — LOSO test signers, WER per condition (mean over seeds)\n")
    conds = IMAGE + FEATURE
    lines.append("| Config | " + " | ".join(conds) + " |")
    lines.append("|---|" + "---:|" * len(conds))
    for c in CONFIGS:
        row = [get(c, "loso", k, "wer") for k in conds]
        if row[0]:
            lines.append(f"| {c} | " + " | ".join(fmt(r["mean"]) if r else "–" for r in row) + " |")

    t = summary["tests"]
    if "primary" in t:
        p = t["primary"]
        sl = p["seed_level"]
        lines.append(f"\n## Primary comparison: {PROPOSED} vs strong baseline {baseline} (LOSO, clean)\n")
        lines.append(f"- Baseline chosen by validation WER from pool: "
                     + ", ".join(f"{k} {v:.1f}" for k, v in sorted(vals.items(), key=lambda x: x[1])))
        lines.append(f"- Seed-averaged corpus WER: proposed {p['wer_a']:.2f} vs baseline {p['wer_b']:.2f}; "
                     f"difference {p['diff']:+.2f} pts, 95% sentence-cluster bootstrap CI [{p['diff_ci'][0]:+.2f}, {p['diff_ci'][1]:+.2f}]")
        lines.append(f"- Relative WER reduction {p['rel_reduction']:+.1f}% (95% CI [{p['rel_ci'][0]:+.1f}, {p['rel_ci'][1]:+.1f}])")
        lines.append(f"- Paired approximate-randomisation test (sequences, {p['n_items']} items): p = {p['perm_p']:.4f}")
        if "signer_signflip_p" in p:
            lines.append(f"- Per-signer differences: " + ", ".join(f"S{k} {v:+.1f}" for k, v in p["per_signer_diff"].items())
                         + f"; exact sign-flip p = {p['signer_signflip_p']:.3f}")
        lines.append(f"- Seed level ({len(p['seeds'])} seeds): {sl['mean_a']:.2f} ± {sl['sd_a']:.2f} vs {sl['mean_b']:.2f} ± {sl['sd_b']:.2f}; "
                     f"mean diff {sl['mean_diff']:+.2f} (95% CI [{sl.get('diff_ci_t', [np.nan] * 2)[0]:+.2f}, {sl.get('diff_ci_t', [np.nan] * 2)[1]:+.2f}]), "
                     f"Wilcoxon p = {sl.get('wilcoxon_p', float('nan')):.4f}, Cohen's d_z = {sl.get('cohen_dz', float('nan')):.2f}, "
                     f"rank-biserial r = {sl.get('rank_biserial', float('nan')):.2f}")
    for fam, title in [("family_R", "Robustness family (LOSO), Holm-corrected"), ("family_G", "Generalisation family, Holm-corrected")]:
        if t.get(fam):
            lines.append(f"\n## {title}: {PROPOSED} minus comparator (negative = proposed better)\n")
            lines.append("| vs | protocol/condition | WER proposed | WER comparator | Δ WER | 95% CI | rel. red. % | p | p (Holm) |")
            lines.append("|---|---|---:|---:|---:|---:|---:|---:|---:|")
            for r in t[fam]:
                lines.append(f"| {r['vs']} | {r.get('protocol', r['cond'])} | {r['wer_a']:.1f} | {r['wer_b']:.1f} | {r['diff']:+.2f} | "
                             f"[{r['diff_ci'][0]:+.1f}, {r['diff_ci'][1]:+.1f}] | {r['rel_reduction']:+.1f} | {r['perm_p']:.4f} | "
                             f"{r['p_holm']:.4f}{' *' if r['reject'] else ''} |")
    if t.get("family_A"):
        a = t["family_A"]
        lines.append(f"\n## Ablation family: Friedman χ² = {a['friedman_chi2']:.1f}, p = {a['friedman_p']:.2e} "
                     f"({len(a['configs'])} configs, {a['n_blocks']} fold×seed blocks)\n")
        lines.append("| Config | mean rank (1 = best) | Δ WER vs proposed (comparator − proposed... see note) | p (Holm) |")
        lines.append("|---|---:|---:|---:|")
        for c in a["configs"]:
            ph = next((x for x in a["posthoc_vs_proposed"] if x["config"] == c), None)
            d_txt = "" if ph is None else f"{-ph['mean_diff']:+.2f}"
            p_txt = "" if ph is None else f"{ph['p_holm']:.4f}"
            lines.append(f"| {c} | {a['mean_ranks'][c]:.2f} | {d_txt} | {p_txt} |")
        lines.append("\nΔ WER = comparator − proposed per block (positive = proposed better).")

    (OUT / "tables.md").write_text("\n".join(lines) + "\n")
    (OUT / "summary.json").write_text(json.dumps(summary, indent=1, default=float))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
